package com.healthupgrades.contract;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import java.lang.annotation.Annotation;
import java.lang.reflect.AnnotatedElement;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Parameter;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.RecordComponent;
import java.lang.reflect.Type;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.SortedMap;
import java.util.TreeMap;
import java.util.UUID;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import org.jspecify.annotations.Nullable;
import org.springframework.beans.factory.config.BeanDefinition;
import org.springframework.context.annotation.ClassPathScanningCandidateComponentProvider;
import org.springframework.core.annotation.AnnotatedElementUtils;
import org.springframework.core.type.filter.AnnotationTypeFilter;
import org.springframework.http.ResponseEntity;
import org.springframework.util.ClassUtils;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Renders the TypeScript declarations of every request and response body the API's controllers
 * declare, so the frontend's wire types are generated rather than written by hand (#168, ADR-053).
 *
 * <p>It walks each handler method's {@code @RequestBody} parameters and its return type, and from there
 * every record and enum they reach. A record becomes an {@code interface}, an enum a union of its
 * constant names, and a component whose type carries JSpecify's {@link Nullable} admits {@code null}.
 * A response always carries every key, because Jackson writes a null rather than leaving it out; a
 * request may leave out a key that admits null, because Jackson binds an absent key as null.
 *
 * <p>The mapping is a closed table. A type outside it, a Jackson annotation it does not model, or a
 * request component whose nullness nothing enforces is a failure, not a guess: a guessed type is the
 * drift this class exists to end.
 */
final class FrontendWireTypes {

    /** The package every controller lives under. */
    static final String API_PACKAGE = "com.healthupgrades";

    /** The Java types Jackson writes as a JSON string, rendered as {@code string}. */
    static final Set<Class<?>> STRINGS =
            Set.of(String.class, UUID.class, LocalDate.class, LocalDateTime.class, LocalTime.class, Instant.class);

    /** The Java types Jackson writes as a JSON number, rendered as {@code number}. */
    static final Set<Class<?>> NUMBERS = Set.of(
            int.class,
            Integer.class,
            long.class,
            Long.class,
            double.class,
            Double.class,
            float.class,
            Float.class,
            short.class,
            Short.class,
            byte.class,
            Byte.class);

    /** The Java types Jackson writes as a JSON boolean, rendered as {@code boolean}. */
    static final Set<Class<?>> BOOLEANS = Set.of(boolean.class, Boolean.class);

    /**
     * The constraints that make a request component non-null. Bean validation runs before a handler is
     * called, so a request without the key, or with a null, is refused with a 400 rather than bound.
     */
    private static final List<Class<? extends Annotation>> NOT_NULL_CONSTRAINTS =
            List.of(NotNull.class, NotBlank.class, NotEmpty.class);

    /** Jackson 3 keeps its annotations in Jackson 2's package; its own classes are under the second. */
    private static final List<String> JACKSON_PACKAGES = List.of("com.fasterxml.jackson.", "tools.jackson.");

    private static final String HEADER = """
            // Generated by FrontendWireTypesContractTest from the request and response records the API's
            // controllers declare (ADR-053). Do not edit it by hand: change the record, then run
            // `npm run generate:wire-types` from the repository root.
            """;

    /** Which way a record crosses the wire, which decides whether a key that admits null may be absent. */
    enum Direction {
        REQUEST("Request body"),
        RESPONSE("Response body");

        private final String label;

        Direction(String label) {
            this.label = label;
        }
    }

    private final Map<String, Class<?>> classesByName = new HashMap<>();
    private final Map<Class<?>, Direction> directions = new HashMap<>();
    private final SortedMap<String, String> enums = new TreeMap<>();
    private final SortedMap<String, String> interfaces = new TreeMap<>();

    private FrontendWireTypes() {}

    /**
     * Every {@code @RestController} under {@link #API_PACKAGE}, found from the classpath without starting
     * a Spring context, so the check stays inside {@code ./mvnw test} (NFR-11).
     *
     * @return the controller classes, ordered by name
     * @throws IllegalStateException if a scanned class cannot be loaded
     */
    static List<Class<?>> apiControllers() {
        ClassPathScanningCandidateComponentProvider scanner = new ClassPathScanningCandidateComponentProvider(false);
        scanner.addIncludeFilter(new AnnotationTypeFilter(RestController.class));
        return scanner.findCandidateComponents(API_PACKAGE).stream()
                .map(BeanDefinition::getBeanClassName)
                .map(FrontendWireTypes::load)
                .sorted(Comparator.comparing(Class::getName))
                .collect(Collectors.toList());
    }

    /**
     * Renders the wire types the given handler classes declare.
     *
     * @param handlerClasses classes whose {@link RequestMapping}-annotated methods are the endpoints
     * @return the TypeScript source: a header, the enums, then the interfaces, each group ordered by name,
     *     with LF line endings and a trailing newline
     * @throws IllegalStateException if a body reaches a type the mapping does not cover, a record is used
     *     both as a request and as a response, two wire types share a simple name, a Jackson annotation
     *     changes a record's JSON, or a request component's nullness is enforced by nothing
     */
    static String render(Collection<Class<?>> handlerClasses) {
        FrontendWireTypes types = new FrontendWireTypes();
        handlerClasses.forEach(types::collect);
        return types.source();
    }

    /**
     * The records the given handler classes reach, each with the direction it crosses the wire in: the
     * same set {@link #render} declares, for a test that holds the rendering rules to the real mapper.
     *
     * @param handlerClasses classes whose {@link RequestMapping}-annotated methods are the endpoints
     * @return every record reached, mapped to whether it is a request or a response body
     * @throws IllegalStateException on anything {@link #render} refuses
     */
    static Map<Class<?>, Direction> records(Collection<Class<?>> handlerClasses) {
        FrontendWireTypes types = new FrontendWireTypes();
        handlerClasses.forEach(types::collect);
        return Map.copyOf(types.directions);
    }

    private void collect(Class<?> handlerClass) {
        // Spring MVC maps an inherited handler and an interface's default method, and honours a
        // @RequestBody declared on an interface's parameter. Reading only this class's own methods would
        // miss all three without a sound, so a controller that could have any of them is refused instead.
        if (handlerClass.getSuperclass() != Object.class || handlerClass.getInterfaces().length > 0) {
            throw new IllegalStateException(handlerClass.getName() + " extends or implements a type, so it may"
                    + " inherit endpoints or a @RequestBody that its own methods do not show. Declare them on the"
                    + " controller itself, or teach " + FrontendWireTypes.class.getSimpleName() + " to read them");
        }
        Method[] methods = handlerClass.getDeclaredMethods();
        Arrays.sort(methods, Comparator.comparing(Method::toGenericString));
        for (Method method : methods) {
            if (method.isSynthetic() || !AnnotatedElementUtils.hasAnnotation(method, RequestMapping.class)) {
                continue;
            }
            String endpoint = handlerClass.getSimpleName() + "." + method.getName();
            for (Parameter parameter : method.getParameters()) {
                if (parameter.isAnnotationPresent(RequestBody.class)) {
                    body(parameter.getParameterizedType(), Direction.REQUEST, endpoint + " request body");
                }
            }
            body(method.getGenericReturnType(), Direction.RESPONSE, endpoint + " response body");
        }
    }

    /** A handler's body type, minus the {@code ResponseEntity} around it; an empty body declares nothing. */
    private void body(Type type, Direction direction, String path) {
        Type payload = type;
        if (type instanceof ParameterizedType parameterized && parameterized.getRawType() == ResponseEntity.class) {
            payload = parameterized.getActualTypeArguments()[0];
        }
        if (payload == void.class || payload == Void.class) {
            return;
        }
        typeScript(payload, direction, path);
    }

    private String typeScript(Type type, Direction direction, String path) {
        if (type instanceof ParameterizedType parameterized && parameterized.getRawType() instanceof Class<?> raw) {
            Type[] arguments = parameterized.getActualTypeArguments();
            if (Collection.class.isAssignableFrom(raw)) {
                return typeScript(arguments[0], direction, path + "[]") + "[]";
            }
            if (Map.class.isAssignableFrom(raw)) {
                requireStringKeyed(arguments[0], path);
                return "Record<string, " + typeScript(arguments[1], direction, path + "{}") + ">";
            }
        }
        if (type instanceof Class<?> cls) {
            if (STRINGS.contains(cls)) {
                return "string";
            }
            if (NUMBERS.contains(cls)) {
                return "number";
            }
            if (BOOLEANS.contains(cls)) {
                return "boolean";
            }
            if (cls.isEnum()) {
                return enumeration(cls, path);
            }
            if (cls.isRecord()) {
                return record(cls, direction, path);
            }
        }
        throw new IllegalStateException(path + " is a " + type.getTypeName()
                + ", which has no TypeScript mapping here. Add one to " + FrontendWireTypes.class.getSimpleName()
                + " only if Jackson writes it as a plain JSON value; otherwise give the API a record for it");
    }

    /** JSON object keys are strings, so only a key Jackson writes as its own string has a faithful mapping. */
    private static void requireStringKeyed(Type key, String path) {
        boolean stringKeyed = key == String.class || key == UUID.class || (key instanceof Class<?> c && c.isEnum());
        if (!stringKeyed) {
            throw new IllegalStateException(path + " is a map keyed by " + key.getTypeName()
                    + ". A JSON object's keys are strings, so key it by a String, a UUID or an enum");
        }
    }

    private String enumeration(Class<?> type, String path) {
        String name = claimName(type, path);
        if (!enums.containsKey(name)) {
            rejectJackson(type, type.getCanonicalName());
            List<String> constants = new ArrayList<>();
            // getEnumConstants() is in declaration order; getDeclaredFields() is in no order the JDK promises.
            for (Object constant : type.getEnumConstants()) {
                String constantName = ((Enum<?>) constant).name();
                rejectJackson(constantField(type, constantName), type.getCanonicalName() + "." + constantName);
                constants.add("'" + constantName + "'");
            }
            enums.put(
                    name,
                    "/** " + type.getCanonicalName() + " */\nexport type " + name + " = "
                            + String.join(" | ", constants) + ";\n");
        }
        return name;
    }

    private String record(Class<?> type, Direction direction, String path) {
        String name = claimName(type, path);
        Direction earlier = directions.putIfAbsent(type, direction);
        if (earlier != null) {
            if (earlier != direction) {
                throw new IllegalStateException(type.getCanonicalName() + " is both a request body and a response"
                        + " body, reached last at " + path + ". The two are typed differently, since only a"
                        + " request may leave a key out, so give each direction its own record");
            }
            return name;
        }
        rejectJackson(type, type.getCanonicalName());

        StringBuilder declaration = new StringBuilder()
                .append("/** ")
                .append(direction.label)
                .append(": ")
                .append(type.getCanonicalName())
                .append(" */\nexport interface ")
                .append(name)
                .append(" {\n");
        for (RecordComponent component : type.getRecordComponents()) {
            String componentPath = name + "." + component.getName();
            rejectJackson(component, componentPath);
            boolean nullable = component.getAnnotatedType().isAnnotationPresent(Nullable.class);
            if (direction == Direction.REQUEST
                    && !nullable
                    && !component.getType().isPrimitive()) {
                requireNotNullConstraint(component, componentPath);
            }
            declaration
                    .append("  ")
                    .append(component.getName())
                    .append(direction == Direction.REQUEST && nullable ? "?: " : ": ")
                    .append(typeScript(component.getGenericType(), direction, componentPath))
                    .append(nullable ? " | null" : "")
                    .append(";\n");
        }
        interfaces.put(name, declaration.append("}\n").toString());
        return name;
    }

    /**
     * A request component that is neither {@code @Nullable} nor constrained could be bound as null while
     * its type says it cannot, so it is refused here rather than typed on trust.
     */
    private static void requireNotNullConstraint(RecordComponent component, String path) {
        boolean constrained = NOT_NULL_CONSTRAINTS.stream()
                .anyMatch(constraint -> component.getAccessor().isAnnotationPresent(constraint)
                        || component.getAnnotatedType().isAnnotationPresent(constraint));
        if (!constrained) {
            throw new IllegalStateException(path + " is a request component that nothing keeps from being null."
                    + " Mark it @Nullable if a client may leave it out, or constrain it with @NotNull,"
                    + " @NotBlank or @NotEmpty if it is required");
        }
    }

    /** The frontend has one namespace, so two wire types with one simple name cannot both be declared. */
    private String claimName(Class<?> type, String path) {
        String name = type.getSimpleName();
        Class<?> holder = classesByName.putIfAbsent(name, type);
        if (holder != null && holder != type) {
            throw new IllegalStateException("two wire types are named " + name + ": " + holder.getCanonicalName()
                    + " and " + type.getCanonicalName() + ", reached at " + path
                    + ". The frontend's types share one namespace, so rename one of them");
        }
        return name;
    }

    /**
     * A Jackson annotation can rename, hide, unwrap or reshape what a record writes, and this class models
     * none of that, so it fails rather than render a shape the wire does not have.
     */
    private static void rejectJackson(AnnotatedElement element, String path) {
        Stream<Annotation> annotations = Stream.of(element.getAnnotations());
        if (element instanceof RecordComponent component) {
            annotations = Stream.concat(
                    annotations,
                    Stream.of(
                                    component.getAccessor().getAnnotations(),
                                    component.getAnnotatedType().getAnnotations())
                            .flatMap(Arrays::stream));
        }
        annotations
                .map(annotation -> annotation.annotationType().getName())
                .filter(annotation -> JACKSON_PACKAGES.stream().anyMatch(annotation::startsWith))
                .findFirst()
                .ifPresent(annotation -> {
                    throw new IllegalStateException(path + " carries " + annotation + ", which changes its JSON in"
                            + " a way " + FrontendWireTypes.class.getSimpleName() + " does not model. Model it"
                            + " there, or shape the record so the annotation is not needed");
                });
    }

    private String source() {
        StringBuilder source = new StringBuilder(HEADER);
        Stream.concat(enums.values().stream(), interfaces.values().stream())
                .forEach(declaration -> source.append('\n').append(declaration));
        return source.toString();
    }

    /** The field behind an enum constant, which is where an annotation on the constant lives. */
    private static Field constantField(Class<?> type, String constantName) {
        try {
            return type.getDeclaredField(constantName);
        } catch (NoSuchFieldException e) {
            throw new IllegalStateException(type.getName() + " has no field for its constant " + constantName, e);
        }
    }

    private static Class<?> load(@Nullable String className) {
        if (className == null) {
            throw new IllegalStateException("the classpath scan returned a candidate with no class name");
        }
        try {
            return ClassUtils.forName(className, FrontendWireTypes.class.getClassLoader());
        } catch (ClassNotFoundException e) {
            throw new IllegalStateException("the classpath scan found " + className + " but it would not load", e);
        }
    }
}
